/**
 * Solves every level (or the ones named) and writes src/levels/solutions.ts: the fewest-moves
 * solution of each, whose length is the level's par. Never edit that file by hand.
 *   npx tsx scripts/dev/solveall.ts [level-id ...]
 */
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../../src/levels/levels';
import { SOLUTIONS } from '../../src/levels/solutions';
import { parseLevel } from '../../src/sim/grid';
import { solve } from '../../src/sim/solver';

const only = process.argv.slice(2);
const out: Record<string, string> = {};
for (const level of LEVELS) {
  if (only.length && !only.includes(level.id) && SOLUTIONS[level.id] !== undefined) {
    out[level.id] = SOLUTIONS[level.id];
    continue;
  }
  const t0 = Date.now();
  const r = solve(parseLevel(level), { maxStates: 8_000_000 });
  if (r.solution === null) throw new Error(`${level.id}: ${r.complete ? 'unsolvable' : 'gave up'} after ${r.explored} states`);
  out[level.id] = r.solution;
  console.log(`${level.id.padEnd(20)} par ${String(r.solution.length).padStart(3)}  ${r.explored} states  ${Date.now() - t0}ms`);
}
const body = Object.entries(out)
  .map(([id, s]) => `  '${id}': '${s}',`)
  .join('\n');
writeFileSync(
  new URL('../../src/levels/solutions.ts', import.meta.url),
  `// Generated by scripts/dev/solveall.ts — do not edit.\n// The fewest-moves solution of each level (LURD, uppercase = push); its length is the par.\nexport const SOLUTIONS: Record<string, string> = {\n${body}\n};\n`,
);
